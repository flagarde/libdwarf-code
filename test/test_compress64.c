int main(void) {
    Dwarf_Debug dbg = 0;
    Dwarf_Error err = 0;
    int res  = 0;
    char path[] = "/tmp/libdwarf-chdr-poc-XXXXXX";
    int fd = mkstemp(path);

    if (fd < 0) return 1;
    write(fd, kElf, sizeof kElf);
    close(fd);
    res = dwarf_init_path(path, 0, 0, DW_GROUPNUMBER_ANY,
        0, 0, &dbg, &err);
    unlink(path);
    if (res == DW_DLV_ERROR) {
        dwarf_dealloc_error(dbg, err);
        return 1;
    }
    if (res == DW_DLV_OK) dwarf_finish(dbg);
    return 0;
}
